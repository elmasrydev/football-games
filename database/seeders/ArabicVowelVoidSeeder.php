    private function seedGroup($game, $genre, $data, $answerType)
    {
        $autocompleteMapping = [
            'football' => 'player',
            'actors' => 'actor',
            'movies' => 'movie',
        ];
        $autocompleteType = $autocompleteMapping[$genre->slug] ?? $answerType;

        foreach ($data as $item) {
            $answer = $item[0];
            $hints = array_slice($item, 1);

            // Arabic Vowel Void: Remove Alif, Waw, Ya
            $vowelVoid = preg_replace('/[اأإآوؤيئى]/u', '_', $answer);

            $challenge = Challenge::create([
                'game_id' => $game->id,
                'genre_id' => $genre->id,
                'language' => 'ar',
                'difficulty' => $this->getDifficulty($answer),
                'stimulus_type' => 'scrambled_text',
                'stimulus_data' => [
                    'consonant_display' => $vowelVoid,
                ],
                'answer' => $answer,
                'answer_type' => $answerType,
                'autocomplete_type' => $autocompleteType,
            ]);

            foreach ($hints as $idx => $hint) {
                ChallengeHint::create([
                    'challenge_id' => $challenge->id,
                    'content' => $hint,
                    'sort_order' => $idx,
                ]);
            }
        }
    }

    private function getDifficulty($str)
    {
        $len = mb_strlen($str);
        if ($len < 6) return 'easy';
        if ($len < 10) return 'medium';
        return 'hard';
    }
